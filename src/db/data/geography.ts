/**
 * Reference geography for the pilot region, and the national region list.
 *
 * **Provenance.** Regions are the sixteen administrative regions of Ghana (2019
 * boundaries). The Upper West districts, sub-districts and facilities below are
 * the GHS Upper West establishment list supplied by the client — every district,
 * every sub-district and every facility or unit that appears against a member of
 * staff, with the unit type as the source records it. Where the source names a
 * district without its assembly kind ("Jirapa" rather than "Jirapa Municipal"),
 * the kind and capital come from the published district list.
 *
 * **What this is now.** The complete working geography of the region as the
 * service knows it: 11 districts, 74 sub-districts and 435 facilities and units,
 * up from a seven-sub-district pilot subset that made most of the region
 * unplaceable in the training form. Facility names are the source's, so a person
 * picking their own unit finds the name they would recognise.
 *
 * **What it is not.** Not the DHIMS2 master facility list. The establishment
 * return lists where staff are posted, which is a close but not identical set:
 * a facility with no GHS staff on it does not appear here, and private and
 * mission facilities that are not in the return are absent. It carries no
 * ownership column, so everything is recorded as GHS; correct that from the
 * master list when it arrives. The seeder upserts on (district, name) and
 * (district, sub-district), so a fuller file replaces this one without a
 * migration.
 *
 * Anything not in this file is genuinely unknown here rather than guessed: an
 * invented sub-district would put a real training in the wrong place on a map.
 */

