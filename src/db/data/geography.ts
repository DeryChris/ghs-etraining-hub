/**
 * Unit types. `CHPS_COMPOUND` and `SERVICE_UNIT` were added for this list: a CHPS
 * compound is where most of the region's staff actually work, and the regional
 * stores, workshop, port health and RCH units are neither hospitals nor
 * directorates.
 */
export type SeedFacilityType =
  | "REGIONAL_HOSPITAL"
  | "MUNICIPAL_HOSPITAL"
  | "DISTRICT_HOSPITAL"
  | "POLYCLINIC"
  | "HEALTH_CENTRE"
  | "CHPS_COMPOUND"
  | "CLINIC"
  | "DIRECTORATE"
  | "SERVICE_UNIT"
  | "OTHER";

export interface SeedFacility {
  name: string;
  type: SeedFacilityType;
  /** The sub-district the source places this unit in; null where it names none. */
  subDistrict?: string;
  ownership?: "GHS" | "CHAG" | "OTHER";
}

